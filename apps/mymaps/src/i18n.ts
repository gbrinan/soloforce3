export type MessageKey = keyof (typeof MESSAGES)["ko"];

function detectLocale(): Locale {
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language || ""];
  for (const lang of langs) {
    const l = lang.toLowerCase();
    if (l.startsWith("ko")) return "ko";
    if (l.startsWith("ja")) return "ja";
  }
  return "en";
}

export function readLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "ko" || saved === "en" || saved === "ja") return saved;
  } catch { /* */ }
  return detectLocale();
}

function format(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let msg: string = MESSAGES[locale][key] ?? MESSAGES.ko[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) msg = msg.replace(`{${k}}`, String(v));
  return msg;
}

// 비-React 모듈용: 호출 시점의 로케일로 번역 (이벤트 핸들러·innerHTML·lib 에러 메시지)
export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  return format(readLocale(), key, vars);
}

export function useI18n() {
  const [locale, setLocale] = useState<Locale>(readLocale);
  useEffect(() => {
    // 대시보드에서 언어 변경 시 storage 이벤트로 실시간 반영 (same-origin)
    const onStorage = (e: StorageEvent) => {
      if (e.key === STORAGE_KEY) setLocale(readLocale());
    };
    window.addEventListener("storage", onStorage);
    return () => window.removeEventListener("storage", onStorage);
  }, []);
  const t = (key: MessageKey, vars?: Record<string, string | number>): string => format(locale, key, vars);
  return { locale, t };
}
