export type MessageKey = keyof (typeof MESSAGES)["ko"];

function detectLocale(): Locale {
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language || ""];
  for (const lang of langs) {
    const l = lang.toLowerCase();
    if (l.startsWith("ko")) return "ko";
    if (l.startsWith("ja")) return "ja";
  }
  return "en";
}

function readLocale(): Locale {
  if (typeof window === "undefined") return "ko";
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "ko" || saved === "en" || saved === "ja") return saved;
  } catch {
    /* */
  }
  return detectLocale();
}

export function useI18n() {
  // SSR/hydration 안전: 서버와 첫 클라이언트 렌더는 "ko" 고정, 마운트 후 실제 로케일로 교체.
  const [locale, setLocale] = useState<Locale>("ko");
  useEffect(() => {
    setLocale(readLocale());
    // 대시보드에서 언어 변경 시 storage 이벤트로 실시간 반영 (same-origin)
    const onStorage = (e: StorageEvent) => {
      if (e.key === STORAGE_KEY) setLocale(readLocale());
    };
    window.addEventListener("storage", onStorage);
    return () => window.removeEventListener("storage", onStorage);
  }, []);
  const t = (key: MessageKey, vars?: Record<string, string | number>): string => {
    let msg: string = MESSAGES[locale][key] ?? MESSAGES.ko[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) msg = msg.replace(`{${k}}`, String(v));
    return msg;
  };
  return { locale, t, intlLocale: INTL_LOCALES[locale] };
}

// ── 날짜 로케일화 헬퍼 (Intl 기반 — MESSAGES 키 불필요, 캘린더/요약 공용) ──────
// 하드코딩 "일월화수목금토" 배열 대체. index 0 = 일요일.
export function weekdayShortLabels(locale: Locale): string[] {
  const fmt = new Intl.DateTimeFormat(INTL_LOCALES[locale], { weekday: "short", timeZone: "UTC" });
  // 2023-01-01(UTC)은 일요일 — 여기서 7일간 포맷해 요일 헤더를 만든다.
  return Array.from({ length: 7 }, (_, i) => fmt.format(new Date(Date.UTC(2023, 0, 1 + i))));
}

// "YYYY년 M월" 대응 — ko: 2026년 7월 / en: July 2026 / ja: 2026年7月
export function formatYearMonth(locale: Locale, year: number, month0: number): string {
  return new Intl.DateTimeFormat(INTL_LOCALES[locale], { year: "numeric", month: "long" }).format(new Date(year, month0, 1));
}

// "M월 D일" 대응 — ko: 7월 5일 / en: July 5 / ja: 7月5日
export function formatMonthDay(locale: Locale, year: number, month0: number, day: number): string {
  return new Intl.DateTimeFormat(INTL_LOCALES[locale], { month: "long", day: "numeric" }).format(new Date(year, month0, day));
}

// 주간 범위 라벨 — ko: 2026년 7월 5일~11일 / en: Jul 5 – 11, 2026 / ja: 2026年7月5日～11日
export function formatDateRange(locale: Locale, start: Date, end: Date): string {
  return new Intl.DateTimeFormat(INTL_LOCALES[locale], { year: "numeric", month: "long", day: "numeric" }).formatRange(start, end);
}
